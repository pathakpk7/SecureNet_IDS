class EncryptedTrafficAnalyzer:
    """
    Extracts and evaluates JA3 / JA4 fingerprints on TLS flows.
    """

    @staticmethod
    def compute_ja3(
        tls_version: int,
        ciphers: List[int],
        extensions: List[int],
        elliptic_curves: List[int],
        ec_point_formats: List[int]
    ) -> Dict[str, str]:
        """
        Compute standard JA3 string and MD5 hash according to Salesforce JA3 specification.
        Format: SSLVersion,Cipher,SSLExtension,EllipticCurve,EllipticCurvePointFormat
        """
        ciphers_str = "-".join(str(c) for c in ciphers)
        extensions_str = "-".join(str(e) for e in extensions)
        curves_str = "-".join(str(c) for c in elliptic_curves)
        points_str = "-".join(str(p) for p in ec_point_formats)

        ja3_raw = f"{tls_version},{ciphers_str},{extensions_str},{curves_str},{points_str}"
        ja3_hash = hashlib.md5(ja3_raw.encode("utf-8")).hexdigest()

        return {
            "ja3_raw": ja3_raw,
            "ja3_hash": ja3_hash
        }

    @staticmethod
    def compute_ja4(
        protocol: str = "t",  # 't' for TCP, 'q' for QUIC
        tls_version: str = "13",  # '13' for 1.3, '12' for 1.2
        has_sni: bool = True,
        ciphers: List[int] = None,
        extensions: List[int] = None
    ) -> str:
        """
        Compute JA4 fingerprint string: [protocol][version][sni][ciphers_len][ext_len]_[ciphers_hash]_[exts_hash]
        """
        ciphers = ciphers or []
        extensions = extensions or []

        sni_flag = "d" if has_sni else "i"
        ciphers_count = f"{min(len(ciphers), 99):02d}"
        exts_count = f"{min(len(extensions), 99):02d}"

        part_a = f"{protocol}{tls_version}{sni_flag}{ciphers_count}{exts_count}"

        # Hash of sorted hex ciphers (truncated to 12 hex chars)
        ciphers_hex = ",".join(f"{c:04x}" for c in sorted(ciphers))
        part_b = hashlib.sha256(ciphers_hex.encode("utf-8")).hexdigest()[:12]

        # Hash of sorted hex extensions (truncated to 12 hex chars)
        exts_hex = ",".join(f"{e:04x}" for e in sorted(extensions))
        part_c = hashlib.sha256(exts_hex.encode("utf-8")).hexdigest()[:12]

        return f"{part_a}_{part_b}_{part_c}"

    def analyze_fingerprint(self, ja3_hash: str) -> Dict[str, Any]:
        """
        Evaluate a JA3 hash against threat intelligence database.
        """
        signature = JA3_SIGNATURES.get(ja3_hash.lower())
        if signature:
            is_malicious = signature["threat_level"] in ("CRITICAL", "HIGH")
            return {
                "ja3_hash": ja3_hash,
                "matched": True,
                "signature_name": signature["name"],
                "category": signature["category"],
                "threat_level": signature["threat_level"],
                "is_malicious": is_malicious,
                "description": signature["description"]
            }
        else:
            return {
                "ja3_hash": ja3_hash,
                "matched": False,
                "signature_name": "Unclassified TLS Client",
                "category": "Unknown",
                "threat_level": "LOW",
                "is_malicious": False,
                "description": "Fingerprint not present in threat signature database."
            }

    def inspect_flow(self, flow_data: Dict[str, Any]) -> Dict[str, Any]:
        """
        Convenience method to evaluate a network flow dictionary.
        """
        ja3 = flow_data.get("ja3_hash")
        if not ja3 and "ciphers" in flow_data:
            res = self.compute_ja3(
                tls_version=flow_data.get("tls_version", 771),
                ciphers=flow_data.get("ciphers", []),
                extensions=flow_data.get("extensions", []),
                elliptic_curves=flow_data.get("elliptic_curves", []),
                ec_point_formats=flow_data.get("ec_point_formats", [])
            )
            ja3 = res["ja3_hash"]

        if ja3:
            return self.analyze_fingerprint(ja3)

        return {
            "matched": False,
            "threat_level": "UNKNOWN",
            "is_malicious": False,
            "description": "No TLS ClientHello parameters provided."
        }


